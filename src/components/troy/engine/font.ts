/** Width of a word in glyph columns (a column of space between letters). */
export function textWidth(text: string) {
  return text.length * 6 - 1;
}

/** Whether the pixel at column `u`, row `v` of `text` is lit (0, 0 at the top left). */
export function textPixel(text: string, u: number, v: number) {
  const col = Math.floor(u);
  const row = Math.floor(v);
  if (row < 0 || row > 6 || col < 0) return false;
  const letter = Math.floor(col / 6);
  const x = col % 6;
  if (letter >= text.length || x > 4) return false;
  return GLYPHS[text[letter]]?.[row]?.[x] === "1";
}
